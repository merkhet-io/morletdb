"""Generate sql/pg_morlet--0.3.9--0.3.10.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.9 is released (0.3.12-alpha.1). 0.3.10 replaces morlet_set_level (#440): a level-2 episode keeps a real example,
so a call whose moves would leave a level-2 episode with a representative above level 1 is refused as a whole, and a
representative is locked while it is assigned. It replaces morlet_build_envelopes (#441): after compaction removed
the first windows of a recording, the builder still recognises the grid (every stored window on it, every missing
position one it skips) instead of reading the stride from the first surviving window. It replaces
morlet_enable_row_security and morlet_enable_memory (#438): the episodic-memory tables follow the recordings' row
security like every other companion table, a memory run is visible to the role that started it, and memory enabled
after the helper is covered at once; the update calls morlet_enable_row_security again for every collection already
under it, so existing memory tables are covered without a manual step (a role that cannot alter one of them makes the
update fail and roll back rather than leave it uncovered). The definition is taken verbatim from the generated schema (CREATE OR
REPLACE keeps OIDs, dependencies and privileges), so tests/upgrade.sh and tests/upgrade_from_release.sh find an
upgraded catalog equal to a fresh 0.3.10 installation. The only table changes are those of that call (policies, and the started_by column of existing memory-run tables). The scripts of earlier steps are
frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.9--0.3.10.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.10'" in control, "control file"

FUNCTIONS = ("morlet_set_level",                                    # #440: representatives keep their samples
             "morlet_build_envelopes",                              # #441: the grid survives compaction
             "morlet_enable_row_security", "morlet_enable_memory")  # #438: episodic memory under row security


def definitions(name):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", "CREATE OR REPLACE FUNCTION", schema[start:end]))
    return out


# #438: collections under row security (their chunks table carries the policy morlet_follows_recording) get the
# episodic-memory tables covered now, not on the next manual call.
REAPPLY = r"""DO $morlet_upgrade$
DECLARE c regclass;
BEGIN
  FOR c IN SELECT to_regclass(format('%I.%I',n.nspname,left(cl.relname,-length('_chunks'))))
    FROM pg_policy p JOIN pg_class cl ON cl.oid=p.polrelid JOIN pg_namespace n ON n.oid=cl.relnamespace
    WHERE p.polname='morlet_follows_recording' AND right(cl.relname,7)='_chunks' ORDER BY 1
  LOOP
    IF c IS NOT NULL THEN PERFORM public.morlet_enable_row_security(c); END IF;
  END LOOP;
END $morlet_upgrade$;
"""

script = ("-- pg_morlet 0.3.9 -> 0.3.10 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- morlet_set_level: a level-2 episode keeps a real example; moves that would leave it with a representative\n"
          "-- above level 1 are refused as a whole, and the representative is locked while it is assigned (#440).\n"
          "-- morlet_build_envelopes: the window grid is recognised after compaction removed its first windows (#441).\n"
          "-- morlet_enable_row_security, morlet_enable_memory: episodic memory follows row security (#438); the update\n"
          "-- applies it to every collection already under morlet_enable_row_security (below).\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.10'\" to load this file. \\quit\n\n"
          + "\n\n".join(d for n in FUNCTIONS for d in definitions(n)) + "\n\n" + REAPPLY)
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(FUNCTIONS)} SQL functions")
