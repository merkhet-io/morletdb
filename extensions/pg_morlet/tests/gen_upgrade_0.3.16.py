"""HISTORICAL: frozen 0.3.15 -> 0.3.16 generator; do not rerun."""
"""Generate sql/pg_morlet--0.3.15--0.3.16.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.15 is released (0.4.0-beta.4). 0.3.16 adds morlet_envelope_explain (Rust) and morlet_explain_match (#573): why a
stored window scored as it did, by the scorer's own arithmetic. Everything is taken verbatim from the generated schema,
so tests/upgrade.sh and tests/upgrade_from_release.sh find an upgraded catalog equal to a fresh 0.3.16 installation.
No table changes. The scripts of earlier steps are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.15--0.3.16.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.16'" in control, "control file"

C_FUNCTIONS = ("morlet_envelope_explain",)
NEW = ("morlet_explain_match",)
REPLACED = ()


def definitions(name, replace):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body; CREATE OR REPLACE for an existing function."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        verb = "CREATE OR REPLACE FUNCTION" if replace else "CREATE FUNCTION"
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", verb, schema[start:end]))
    return out


def c_definition(name):
    """The generated definition of a new Rust (C) function, before the SQL function that calls it."""
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, f"{name}: not in the schema"
    return re.sub(r"\s+/\*.*?\*/", "", m.group(0)).replace("CREATE  FUNCTION", "CREATE FUNCTION").rstrip()


script = ("-- pg_morlet 0.3.15 -> 0.3.16 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- morlet_explain_match (#573): why a stored window scored as it did.\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.16'\" to load this file. \\quit\n\n"
          + "\n\n".join([c_definition(n) for n in C_FUNCTIONS] + [d for n in NEW for d in definitions(n, False)]
                        + [d for n in REPLACED for d in definitions(n, True)]) + "\n")
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(C_FUNCTIONS) + len(NEW)} new and {len(REPLACED)} replaced SQL functions")
