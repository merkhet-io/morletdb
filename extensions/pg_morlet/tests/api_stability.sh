#!/usr/bin/env bash
# API stability gate (#195, docs/api-stability.md). Against the installed extension:
#  1. every function and aggregate of pg_morlet is classified in api/functions.tsv;
#  2. every stable signature in api/stable.txt still exists unchanged (arguments and result);
#  3. every function classified stable is in api/stable.txt (a new stable function is added there deliberately).
# Regenerate the snapshot after a deliberate, documented change:  tests/api_stability.sh --write
set -euo pipefail
. "$(dirname "$0")/pg_env.sh"  # PG_CONFIG, PG_MAJOR, PORT, BIN
EXT=$(cd "$(dirname "$0")/.." && pwd)
DB=morlet_api_stability
psql() { "$BIN/psql" -h localhost -p "$PORT" -v ON_ERROR_STOP=1 -qAtX "$@"; }
psql -d postgres -c "DROP DATABASE IF EXISTS $DB" -c "CREATE DATABASE $DB"
trap 'psql -d postgres -c "DROP DATABASE IF EXISTS $DB" >/dev/null' EXIT
psql -d "$DB" -c "CREATE EXTENSION pg_morlet"
WORK=$(mktemp -d)
psql -d "$DB" > "$WORK/all.txt" <<'SQL'
SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ') -> ' ||
       CASE WHEN p.prokind = 'a' THEN 'aggregate ' ELSE '' END || coalesce(pg_get_function_result(p.oid), '')
FROM pg_proc p JOIN pg_depend d ON d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e'
JOIN pg_extension e ON e.oid = d.refobjid AND e.extname = 'pg_morlet' ORDER BY 1;
SQL
grep -v '^#' "$EXT/api/functions.tsv" | cut -f1,2 > "$WORK/classes.tsv"
fail=0
while read -r sig; do
  name=${sig%%(*}
  grep -q "^$name	" "$WORK/classes.tsv" || { echo "UNCLASSIFIED $name: add it to api/functions.tsv"; fail=1; }
done < "$WORK/all.txt"
awk -F'\t' '$2=="stable"{print $1}' "$WORK/classes.tsv" > "$WORK/stable_names.txt"
grep -F -f <(sed 's/$/(/' "$WORK/stable_names.txt") "$WORK/all.txt" | while read -r sig; do
  n=${sig%%(*}; grep -qx "$n" "$WORK/stable_names.txt" && echo "$sig"; done | sort > "$WORK/stable_now.txt"
if [ "${1:-}" = --write ]; then
  { echo "# Stable signatures of pg_morlet (docs/api-stability.md); generated by tests/api_stability.sh --write"
    cat "$WORK/stable_now.txt"; } > "$EXT/api/stable.txt"
  echo "wrote api/stable.txt ($(wc -l < "$WORK/stable_now.txt") signatures)"; rm -rf "$WORK"; exit 0
fi
grep -v '^#' "$EXT/api/stable.txt" | sort > "$WORK/stable_snapshot.txt"
if ! diff -u "$WORK/stable_snapshot.txt" "$WORK/stable_now.txt" > "$WORK/diff.txt"; then
  echo "STABLE API CHANGED (- in the snapshot, + now). A stable signature may only change after a deprecation"
  echo "cycle (docs/api-stability.md); if this change is deliberate, run tests/api_stability.sh --write."
  sed -n '3,$p' "$WORK/diff.txt"; fail=1
fi
rm -rf "$WORK"
[ "$fail" -eq 0 ] && echo "api stability: PASS ($(grep -vc '^#' "$EXT/api/stable.txt") stable signatures, all functions classified)"
exit "$fail"
