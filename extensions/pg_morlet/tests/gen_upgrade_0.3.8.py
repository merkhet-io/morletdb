"""HISTORICAL. Generated sql/pg_morlet--0.3.7--0.3.8.sql, which is frozen as released in 0.3.10-alpha.1.
Do not re-run: the control file now names a later version. Newer scripts come from tests/gen_upgrade.py.

Generate sql/pg_morlet--0.3.7--0.3.8.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.7 is released (0.3.9-alpha.1). 0.3.8 fixes how rates become exact numbers (#343): `sample_rate_hz::numeric`
rounds a float8 to 15 significant digits (1/60 Hz -> 0.0166666666666667, slightly above 1/60), so a time exactly at a
sample instant mapped to the next sample. A rate is now read as the exact fraction it stands for (morlet_rate_ratio:
1/60, 1/7, 25600/1, or its exact decimal), and sample boundaries are computed in integer arithmetic
(morlet_ns_to_samples, morlet_samples_to_ns). The script creates those three functions and replaces the ones that
convert rates, and morlet_interval_stats, which takes a fast path for intervals shorter than a roll-up block
(#346), taking each definition verbatim from the
generated schema (CREATE OR REPLACE keeps OIDs, dependencies and privileges), so tests/upgrade.sh and
tests/upgrade_from_release.sh find an upgraded catalog equal to a fresh 0.3.8 installation. No signature, table or
data changes. The scripts of earlier steps are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.7--0.3.8.sql"
FUNCTIONS = ("morlet_rate_ratio", "morlet_ns_to_samples", "morlet_samples_to_ns",   # new in 0.3.8, used below
             "morlet_interval_stats",                      # #346: the fast path for short intervals
             "morlet_interval_buckets",                    # #340: jit=off
             "morlet_time_to_samples", "morlet_sample_time_ns", "morlet_time_bounds", "morlet_before_ns",
             "morlet_history_sql", "morlet_search_similar_evidence", "morlet_build_acquisition_segments")
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.8'" in control, "control file"

def definitions(name):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", "CREATE OR REPLACE FUNCTION", schema[start:end]))
    return out


def c_definition(name):
    """The generated definition of a new Rust (C) function, before the SQL functions that call it."""
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, f"{name}: not in the schema"
    return re.sub(r"\s+/\*.*?\*/", "", m.group(0)).replace("CREATE  FUNCTION", "CREATE FUNCTION").rstrip()

C_FUNCTIONS = ("morlet_interval_stats_fast",)                 # #346: single-bucket statistics with a cached plan
defs = [c_definition(name) for name in C_FUNCTIONS] + [d for name in FUNCTIONS for d in definitions(name)]
leftover = re.findall(r"(?:sample_rate_hz|\brate)::numeric", schema)
assert not leftover, f"rates still converted with float8::numeric: {len(leftover)}"

script = ("-- pg_morlet 0.3.7 -> 0.3.8 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- Rates as exact fractions (#343): float8::numeric rounded 1/60 Hz to 15 digits, so a time exactly at a\n"
          "-- sample instant mapped to the next sample. Adds morlet_rate_ratio, morlet_ns_to_samples and\n"
          "-- morlet_samples_to_ns, and replaces the functions that convert rates. Adds morlet_interval_stats_fast, the\n"
          "-- fast path of morlet_interval_stats for short intervals (#346).\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.8'\" to load this file. \\quit\n\n"
          + "\n\n".join(defs) + "\n")
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(defs)} functions")
