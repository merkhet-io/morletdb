"""Generate sql/pg_morlet--0.3.5--0.3.6.sql from streams.sql and the generated 0.3.6 schema
(cargo pgrx schema pg17 -o NEW.sql). Usage: gen_upgrade.py NEW.sql [--check]
(--check compares instead of writing and fails when the committed script is stale)

0.3.5 is released (0.3.7-alpha.1); its objects are known. 0.3.6 makes history comparisons count independent
observations only (#224): morlet_history_sql keeps segments of the query segment's segmentation spec and drops
segments that overlap the query segment's own samples (body changes, signature does not). It adds morlet_coverage
(#215): which samples a search can find, per recording and state, and morlet_latest (#206): the newest samples
or chunk statistics of every recording. No data or policy changes.
tests/upgrade.sh and tests/upgrade_from_release.sh check that an upgraded catalog equals a fresh 0.3.6
installation. The scripts of earlier steps (0.3.4 -> 0.3.5 and before) are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


def rust(name):
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, name
    return m.group(0).replace("CREATE  FUNCTION", "CREATE FUNCTION")


NEW_RUST = []
NEW_SQL = ["morlet_coverage", "morlet_latest"]
CHANGED = ["morlet_history_sql"]
# Signature changed: the 0.3.5 function (these argument types) is dropped and created again.
RECREATED = {}

out = ["""-- pg_morlet 0.3.5 (as released in 0.3.7-alpha.1) -> 0.3.6.
-- Generated by tests/gen_upgrade.py. Data and policies are not modified.
"""]
out += [rust(r) for r in NEW_RUST]
out += [fn(r) for r in NEW_SQL]
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1) for r in CHANGED]
out += [f"DROP FUNCTION public.{r}({args});\n" + fn(r) for r, args in RECREATED.items()]
target = EXT / "sql/pg_morlet--0.3.5--0.3.6.sql"
if CHECK:
    if target.read_text() != "\n".join(out):
        sys.exit(f"{target.name} is stale: regenerate it with tests/gen_upgrade.py")
    print(f"{target.name} is up to date")
else:
    target.write_text("\n".join(out))
