"""Generate sql/pg_morlet--0.3.14--0.3.15.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.14 is released (0.4.0-beta.3). 0.3.15 fixes morlet_time_pieces on collections without a time-anchor table (#562):
it read a field of a record that was never assigned, so morlet_sample_utc, morlet_utc_to_sample(s) and the SDK's
time_ranges failed there instead of falling back to start time and rate. CREATE OR REPLACE keeps its OID,
dependencies and privileges. Everything is taken verbatim from the generated schema, so tests/upgrade.sh and
tests/upgrade_from_release.sh find an upgraded catalog equal to a fresh 0.3.15 installation. No table changes. The
scripts of earlier steps are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.14--0.3.15.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.15'" in control, "control file"

NEW = ()
REPLACED = ("morlet_time_pieces",)     # #562: no record field read without an anchor table


def definitions(name, replace):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body; CREATE OR REPLACE for an existing function."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        verb = "CREATE OR REPLACE FUNCTION" if replace else "CREATE FUNCTION"
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", verb, schema[start:end]))
    return out


script = ("-- pg_morlet 0.3.14 -> 0.3.15 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- morlet_time_pieces (#562): falls back to start time and rate on collections without a time-anchor table.\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.15'\" to load this file. \\quit\n\n"
          + "\n\n".join([d for n in NEW for d in definitions(n, False)]
                        + [d for n in REPLACED for d in definitions(n, True)]) + "\n")
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(NEW)} new and {len(REPLACED)} replaced SQL functions")
