"""Generate sql/pg_morlet--0.3.0--0.3.1.sql from streams.sql and the generated 0.3.1 schema
(cargo pgrx schema pg17 -o NEW.sql). Usage: gen_upgrade.py NEW.sql

0.3.0 is released (0.3.0-alpha.1); its objects are known. The script adds new functions and
replaces bodies that changed. tests/upgrade.sh and tests/upgrade_from_release.sh check that
an upgraded catalog equals a fresh 0.3.1 installation."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()
schema = Path(sys.argv[1]).read_text()


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


def rust(name):
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, name
    return m.group(0).replace("CREATE  FUNCTION", "CREATE FUNCTION")


# Filled in as 0.3.1 changes land.
NEW_RUST = ["morlet_simple_value_floors", "morlet_decode_interval", "morlet_envelope_probe"]
CHANGED_BODY = ["morlet_value_spreads", "morlet_compare_to_history", "morlet_history_neighbors",
                "morlet_stream_relations", "morlet_read_interval", "morlet_build_envelopes"]
NEW_SQL = ["morlet_level_track", "morlet_envelope_probe_relation", "morlet_enable_envelope_probes",
           "morlet_search_envelope_probes"]

out = ["""-- pg_morlet 0.3.0 (as released in 0.3.0-alpha.1) -> 0.3.1.
-- Generated by tests/gen_upgrade.py. Existing collections and data are not modified.
"""]
out += [rust(r) for r in NEW_RUST]
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1) for r in CHANGED_BODY]
out += [fn(r) for r in NEW_SQL]
(EXT / "sql/pg_morlet--0.3.0--0.3.1.sql").write_text("\n".join(out))
