"""Generate sql/pg_morlet--0.3.1--0.3.2.sql from streams.sql. Usage: gen_upgrade.py

0.3.1 is released (0.3.1-alpha.1); its objects are known. The script replaces bodies and defaults that
changed and adds new functions; no Rust function changed its SQL signature. tests/upgrade.sh and
tests/upgrade_from_release.sh check that an upgraded catalog equals a fresh 0.3.2 installation."""
import re
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


# Filled in as 0.3.2 changes land. CREATE OR REPLACE also changes parameter defaults.
CHANGED = ["morlet_envelope_ranked", "morlet_search_envelopes", "morlet_search_envelope_interval"]
NEW_SQL = ["morlet_search_similar"]

out = ["""-- pg_morlet 0.3.1 (as released in 0.3.1-alpha.1) -> 0.3.2.
-- Generated by tests/gen_upgrade.py. Existing collections and data are not modified.
"""]
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1) for r in CHANGED]
out += [fn(r) for r in NEW_SQL]
(EXT / "sql/pg_morlet--0.3.1--0.3.2.sql").write_text("\n".join(out))
