"""Generate sql/pg_morlet--0.3.2--0.3.3.sql from streams.sql and the generated 0.3.3 schema
(cargo pgrx schema pg17 -o NEW.sql). Usage: gen_upgrade.py NEW.sql [--check]
(--check compares instead of writing and fails when the committed script is stale)

0.3.2 is released (0.3.2-alpha.1 and 0.3.3-alpha.1); its objects are known. The script adds new Rust
and SQL functions and the morlet_envelope_screen aggregate, and replaces the body of
morlet_envelope_ranked (screened exact search); no existing function changes its signature. tests/upgrade.sh and
tests/upgrade_from_release.sh check that an upgraded catalog equals a fresh 0.3.3 installation."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


def rust(name):
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, name
    return m.group(0).replace("CREATE  FUNCTION", "CREATE FUNCTION")


# Filled in as 0.3.3 changes land.
NEW_RUST = ["morlet_float8_from_le_bytes", "morlet_decode_interval_raw",
            "morlet_envelope_screen_step", "morlet_envelope_screen_combine", "morlet_envelope_screen_serial",
            "morlet_envelope_screen_deserial", "morlet_envelope_screen_final", "morlet_float8_le_bytes",
            "morlet_chunk_summary", "morlet_encoded_chunk_summary", "morlet_chunk_summary_values",
            "morlet_interval_stats_step", "morlet_interval_stats_final", "morlet_samples_overview"]
CHANGED = ["morlet_append_chunk", "morlet_enable_row_security", "morlet_add_acquisition_channel"]
# Signature or return type changed: the 0.3.2 function (these argument types) is dropped and created again.
RECREATED = {
    "morlet_stream_relations": "regclass",
    "morlet_envelope_ranked": "regclass,float8[],float8,text,text,jsonb,integer,float8,boolean,integer,text,bigint,bigint",
    "morlet_search_envelopes": "regclass,float8[],float8,text,text,jsonb,integer,float8,boolean,integer",
    "morlet_search_envelope_interval": "regclass,text,bigint,bigint,jsonb,integer,float8,boolean,boolean,integer",
    "morlet_search_envelope_probes": "regclass,text,bigint,bigint,jsonb,integer,float8,boolean,boolean,integer,integer,integer",
    "morlet_search_similar": "regclass,text,bigint,bigint,jsonb,integer,float8,boolean,boolean,integer",
}
NEW_SQL = ["morlet_append_chunk_raw", "morlet_read_interval_raw", "morlet_interval_stats", "morlet_check_candidates",
           "morlet_interval_buckets", "morlet_interval_overview", "morlet_enable_chunk_summaries", "morlet_build_chunk_summaries",
           "morlet_read_acquisition_raw",
           "morlet_recording_start_ns", "morlet_time_bounds", "morlet_time_ns", "morlet_before_ns",
           "morlet_search_similar_evidence", "morlet_inserted_by_current_transaction",
           "morlet_acquisition_has_visible_channel"]

out = ["""-- pg_morlet 0.3.2 (as released in 0.3.2-alpha.1 and 0.3.3-alpha.1) -> 0.3.3.
-- Generated by tests/gen_upgrade.py. Data is not modified; collections that use morlet_enable_row_security
-- get the current companion-table policies (acquisition channels need a visible acquisition).
"""]
out += [rust(r) for r in NEW_RUST]
out += [fn(r) for r in NEW_SQL]
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1) for r in CHANGED]
out += [f"DROP FUNCTION public.{r}({args});\n" + fn(r) for r, args in RECREATED.items()]
aggs = re.findall(r"(?:--[^\n]*\n)*CREATE AGGREGATE public\.\w+\(.*?\);\n", streams, re.S)
assert len(aggs) == 2, aggs
out += aggs
# Re-apply row security where it is in use, so existing acquisition tables get the 0.3.3 policies.
out.append("""DO $$
DECLARE c regclass;
BEGIN
  FOR c IN SELECT to_regclass(format('%I.%I',n.nspname,left(cl.relname,length(cl.relname)-13)))
      FROM pg_class cl JOIN pg_namespace n ON n.oid=cl.relnamespace
      WHERE cl.relkind='r' AND cl.relname LIKE '%\\_acq\\_channels' LOOP
    IF c IS NOT NULL AND public.morlet_row_security_enabled(c) THEN PERFORM public.morlet_enable_row_security(c); END IF;
  END LOOP;
END $$;
""")
target = EXT / "sql/pg_morlet--0.3.2--0.3.3.sql"
if CHECK:
    if target.read_text() != "\n".join(out):
        sys.exit(f"{target.name} is stale: regenerate it with tests/gen_upgrade.py")
    print(f"{target.name} is up to date")
else:
    target.write_text("\n".join(out))
