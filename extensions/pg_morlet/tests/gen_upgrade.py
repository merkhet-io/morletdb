"""Generate sql/pg_morlet--0.3.6--0.3.7.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.6 is released (0.3.8-alpha.1); its objects are known. 0.3.7 changes no object but where the C functions find
their library (#315): module_pathname is 'pg_morlet' instead of '$libdir/pg_morlet', so PostgreSQL searches
dynamic_library_path (default '$libdir', so ordinary installations are unchanged) and the extension can be loaded
from a directory named in extension_control_path (PostgreSQL 18 and later), such as an image volume. A fresh 0.3.7
installation stores 'pg_morlet' as each C function's library; the update redefines every C function of the
extension that still names '$libdir/pg_morlet' with CREATE OR REPLACE (same OIDs, dependencies and privileges; no
catalog edits), so tests/upgrade.sh and tests/upgrade_from_release.sh still find an upgraded catalog equal to a fresh
0.3.7 installation. The scripts of earlier steps (0.3.5 -> 0.3.6 and before) are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.6--0.3.7.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]

# Every C function the generated schema defines must name its library through MODULE_PATHNAME, which the control
# file's module_pathname replaces; otherwise the update below would not cover it.
c_libs = re.findall(r"LANGUAGE c\b.*?AS '([^']*)'", schema, re.S | re.I)
assert c_libs, "no C functions in the generated schema"
others = sorted(set(c_libs) - {"MODULE_PATHNAME"})
assert not others, f"C functions name a library other than MODULE_PATHNAME: {others}"
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.7'" in control and "module_pathname = 'pg_morlet'" in control, "control file"

script = r"""-- pg_morlet 0.3.6 -> 0.3.7 (generated by tests/gen_upgrade.py; do not edit).
-- The C functions find their library through dynamic_library_path (#315): module_pathname is now 'pg_morlet'
-- instead of '$libdir/pg_morlet'. Redefine every C function of the extension that still names the old path;
-- CREATE OR REPLACE keeps OIDs, dependencies and privileges. No data, table or policy changes.
\echo Use "ALTER EXTENSION pg_morlet UPDATE TO '0.3.7'" to load this file. \quit

DO $morlet_upgrade$
DECLARE
  f regprocedure;
  def text;
  n integer := 0;
BEGIN
  FOR f IN
    SELECT p.oid::regprocedure
    FROM pg_proc p
    JOIN pg_depend d ON d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e'
    JOIN pg_extension e ON e.oid = d.refobjid AND e.extname = 'pg_morlet'
    WHERE p.prolang = (SELECT oid FROM pg_language WHERE lanname = 'c')
      AND p.probin = '$libdir/pg_morlet'
    ORDER BY p.oid
  LOOP
    def := pg_get_functiondef(f);
    IF position(E'\nAS ''$libdir/pg_morlet'', ' IN def) = 0 THEN
      RAISE EXCEPTION 'pg_morlet update: unexpected definition of %', f;
    END IF;
    EXECUTE replace(def, E'\nAS ''$libdir/pg_morlet'', ', E'\nAS ''pg_morlet'', ');
    n := n + 1;
  END LOOP;
  IF EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_depend d ON d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e'
    JOIN pg_extension e ON e.oid = d.refobjid AND e.extname = 'pg_morlet'
    WHERE p.probin IS DISTINCT FROM 'pg_morlet'
      AND p.prolang = (SELECT oid FROM pg_language WHERE lanname = 'c')
  ) THEN
    RAISE EXCEPTION 'pg_morlet update: a C function still names another library';
  END IF;
  RAISE NOTICE 'pg_morlet 0.3.7: % C functions now load pg_morlet through dynamic_library_path', n;
END
$morlet_upgrade$;
"""

if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py NEW.sql")
    print(f"{OUT.name} is current ({len(c_libs)} C functions in the schema)")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name} ({len(c_libs)} C functions in the schema)")
