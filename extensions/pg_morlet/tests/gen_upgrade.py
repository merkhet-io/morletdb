"""Generate sql/pg_morlet--0.2.0--0.3.0.sql from streams.sql and the generated 0.3.0 schema
(cargo pgrx schema pg17 -o NEW.sql). Usage: gen_upgrade.py NEW.sql

0.2.0 is released (0.2.0-alpha.1); its objects are known. The script adds new functions,
drops and recreates functions whose signature or return type changed, and replaces bodies
that changed. tests/upgrade.sh and tests/upgrade_from_0.2.0.sh check that an upgraded catalog
equals a fresh 0.3.0 installation."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()
schema = Path(sys.argv[1]).read_text()


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


def rust(name):
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, name
    return m.group(0).replace("CREATE  FUNCTION", "CREATE FUNCTION")


# Filled in as 0.3.0 changes land.
NEW_SQL = ["morlet_enable_acquisitions", "morlet_acquisition_relations", "morlet_time_to_samples",
           "morlet_sample_time_ns", "morlet_create_acquisition", "morlet_add_acquisition_channel",
           "morlet_segment_start_ns", "morlet_add_acquisition_context", "morlet_read_acquisition",
           "morlet_compare_acquisition", "morlet_build_acquisition_segments",
           "morlet_history_neighbors"]
NEW_RUST = []
CHANGED_SIGNATURE = {   # name -> old identity argument list, dropped before recreation
    "morlet_history_sql": "regclass,boolean",
    "morlet_value_spreads": "regclass,bigint,jsonb,text[],integer,double precision",
    "morlet_compare_to_history": "regclass,bigint,text[],jsonb,text[],integer,integer",
    "morlet_compare_summary": "regclass,bigint,text[],jsonb,text[],integer,integer",
    "morlet_build_context_segments": "regclass,text,text[],text[],integer",
}
CHANGED_BODY = []

out = ["""-- pg_morlet 0.2.0 (as released in 0.2.0-alpha.1) -> 0.3.0.
-- Generated by tests/gen_upgrade.py. Existing collections and data are not modified.
"""]
out += [rust(r) for r in NEW_RUST]
for name, args in CHANGED_SIGNATURE.items():
    out.append(f"DROP FUNCTION public.{name}({args});\n")
out += [fn(r) for r in NEW_SQL + list(CHANGED_SIGNATURE)]
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1) for r in CHANGED_BODY]
(EXT / "sql/pg_morlet--0.2.0--0.3.0.sql").write_text("\n".join(out))
