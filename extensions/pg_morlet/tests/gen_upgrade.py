"""Generate sql/pg_morlet--0.3.13--0.3.14.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.13 is released (0.4.0-beta.2). 0.3.14 adds stream_keys to morlet_latest (#527): only the newest recording of each
stream, so a collector's daily recordings no longer make "latest" read every day it has stored. A new trailing
argument with a default is a new signature, so the 0.3.13 function is dropped first and the new one created from the
generated schema (morlet_latest is experimental; calls with up to four arguments keep their results). Everything is
taken verbatim from the generated schema, so tests/upgrade.sh and tests/upgrade_from_release.sh find an upgraded catalog
equal to a fresh 0.3.14 installation. No table changes. The scripts of earlier steps are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.13--0.3.14.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.14'" in control, "control file"

# #527: morlet_latest's 0.3.13 signature, dropped before the new one (with stream_keys) is created
DROPPED = ("DROP FUNCTION public.morlet_latest(regclass,integer,jsonb,integer);",)
NEW = ("morlet_latest",)
REPLACED = ()


def definitions(name, replace):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body; CREATE OR REPLACE for an existing function."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        verb = "CREATE OR REPLACE FUNCTION" if replace else "CREATE FUNCTION"
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", verb, schema[start:end]))
    return out


script = ("-- pg_morlet 0.3.13 -> 0.3.14 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- morlet_latest gains stream_keys (#527): the newest recording of each stream; a new signature, so the\n"
          "-- 0.3.13 function is dropped first.\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.14'\" to load this file. \\quit\n\n"
          + "\n\n".join(list(DROPPED) + [d for n in NEW for d in definitions(n, False)]
                        + [d for n in REPLACED for d in definitions(n, True)]) + "\n")
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(NEW)} new, {len(REPLACED)} replaced and {len(DROPPED)} dropped SQL functions")
