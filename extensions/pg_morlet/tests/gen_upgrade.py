"""Regenerate sql/pg_morlet--0.1.0--0.2.0.sql from streams.sql and the generated
0.2.0 schema (cargo pgrx schema pg17 -o NEW.sql). Usage: gen_upgrade.py NEW.sql"""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
streams = (EXT / "sql/streams.sql").read_text()
schema = Path(sys.argv[1]).read_text()


def fn(name):
    m = re.search(r"(?:--[^\n]*\n)*CREATE FUNCTION public\." + name + r"\(.*?\n(?:END )?\$\$;\n", streams, re.S)
    assert m, name
    return m.group(0)


def rust(name):
    m = re.search(r'CREATE  FUNCTION "' + name + r'"\(.*?;\n', schema, re.S)
    assert m, name
    return m.group(0).replace("CREATE  FUNCTION", "CREATE FUNCTION")


out = ["""-- pg_morlet 0.1.0 (as released in 0.1.0-alpha.3) -> 0.2.0: encoded stream chunks.
-- Generated by tests/gen_upgrade.py. Existing collections and their data are not
-- modified; they keep float8[] chunks and work unchanged. Only collections
-- created after the update use encoded storage. tests/upgrade.sh checks that the
-- upgraded catalog equals a fresh 0.2.0 installation.
DO $$
BEGIN
  -- 0.1.0-alpha.1 also called itself 0.1.0 but lacks the versioned extractor API.
  IF to_regprocedure('morlet_chunk_checkpoint(double precision,integer,integer,text,text)') IS NULL
    OR to_regprocedure('morlet_append_chunks(regclass,text,morlet_input_chunk[])') IS NULL THEN
    RAISE EXCEPTION 'pg_morlet 0.1.0 objects predate 0.1.0-alpha.3; this update supports alpha.3 only (see docs/durable-ingestion.md, Upgrading)';
  END IF;
END $$;

-- New chunk codec entry points (Rust).
"""]
out += [rust(r) for r in ("morlet_encode_chunk", "morlet_decode_chunk", "morlet_encoded_chunk_kind",
                          "morlet_valid_encoded_chunk")]
out.append("\n-- Return type changed: drop and recreate. PL/pgSQL callers resolve it at run time.\n"
           "DROP FUNCTION public.morlet_stream_relations(regclass);\n")
out.append(fn("morlet_stream_relations"))
out.append("\n-- Signatures gained a trailing sample_quantum argument.\n"
           "DROP FUNCTION public.morlet_start_recording(regclass,text,double precision,text,text,jsonb,integer,integer,text,text);\n"
           "DROP FUNCTION public.morlet_ensure_recording(regclass,text,double precision,text,text,jsonb,integer,integer,text,text);\n")
out += [fn("morlet_start_recording"), fn("morlet_ensure_recording")]
out.append("\n-- Bodies changed; signatures unchanged.\n")
out += [fn(r).replace("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.", 1)
        for r in ("morlet_create_stream_collection", "morlet_append_chunk", "morlet_read_interval")]
out.append("\n-- New storage reports.\n")
out += [fn("morlet_recording_storage"), fn("morlet_collection_storage")]
out.append("\n-- Materialized envelopes (xc-envelope-f16-v1).\n")
out += [rust(r) for r in ("morlet_envelope_version", "morlet_envelope", "morlet_envelope_encode",
                          "morlet_envelope_decode", "morlet_envelope_distance")]
out += [fn(r) for r in ("morlet_enable_envelopes", "morlet_envelope_relation", "morlet_build_envelopes",
                        "morlet_envelope_ranked", "morlet_search_envelopes", "morlet_search_envelope_interval")]
out.append("\n-- Context model, phase 1.\n")
out += [rust(r) for r in ("morlet_simple_values", "morlet_simple_value_names", "morlet_simple_values_version")]
out += [fn(r) for r in ("morlet_enable_context", "morlet_context_relations", "morlet_check_context_overlaps",
                        "morlet_add_context", "morlet_revise_context", "morlet_build_context_segments",
                        "morlet_build_context_values", "morlet_add_label", "morlet_retract_label",
                        "morlet_compare_to_history")]
(EXT / "sql/pg_morlet--0.1.0--0.2.0.sql").write_text("\n".join(out))
