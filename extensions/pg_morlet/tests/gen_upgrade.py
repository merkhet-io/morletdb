"""Generate sql/pg_morlet--0.3.12--0.3.13.sql. Usage: gen_upgrade.py NEW.sql [--check]
(NEW.sql from `cargo pgrx schema pg17 -o NEW.sql`; --check compares instead of writing and fails when the committed
script is stale)

0.3.12 is released (0.4.0-beta.1). 0.3.13 adds time anchors (#393, #383; docs/clock-drift.md): an opt-in companion table
<collection>_time_anchors created by morlet_enable_time_anchors, idempotent batches (morlet_add_time_anchors) and
revisions (morlet_revise_time_anchor), and the exact mapping between samples and UTC time with segments and breaks
(morlet_sample_utc, morlet_utc_to_samples, morlet_utc_to_sample, morlet_time_axis_version), all new. It replaces
morlet_enable_row_security, which covers the anchor table (same signature; CREATE OR REPLACE keeps OIDs, dependencies
and privileges). Everything is taken verbatim from the generated schema, so tests/upgrade.sh and
tests/upgrade_from_release.sh find an upgraded catalog equal to a fresh 0.3.13 installation. No existing table changes.
The scripts of earlier steps are frozen."""
import re
import sys
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent
OUT = EXT / "sql/pg_morlet--0.3.12--0.3.13.sql"
schema = Path(sys.argv[1]).read_text()
CHECK = "--check" in sys.argv[2:]
control = (EXT / "pg_morlet.control").read_text()
assert "default_version = '0.3.13'" in control, "control file"

NEW = ("morlet_enable_time_anchors", "morlet_time_anchor_relation",  # in dependency order
       "morlet_lock_time_anchors", "morlet_json_bigint", "morlet_check_time_anchors", "morlet_time_anchors_lock",
       "morlet_time_anchors_inserted", "morlet_time_anchors_append_only", "morlet_add_time_anchors",
       "morlet_revise_time_anchor", "morlet_default_clock_rho", "morlet_time_pieces", "morlet_piece_uncertainty",
       "morlet_sample_utc", "morlet_piece_ceil", "morlet_utc_to_samples", "morlet_utc_to_sample",
       "morlet_time_axis_version")
REPLACED = ("morlet_enable_row_security",)  # covers <collection>_time_anchors


def definitions(name, replace):
    """Every CREATE FUNCTION public.<name>(...) statement of the schema (overloads in schema order), each through the
    end of its dollar-quoted body; CREATE OR REPLACE for an existing function."""
    starts = [m.start() for m in re.finditer(r"^CREATE (?:OR REPLACE )?FUNCTION public\." + name + r"\(", schema, re.M)]
    assert starts, f"{name}: not in the schema"
    out = []
    for start in starts:
        body = re.compile(r"\bAS\s+(\$\w*\$)").search(schema, start)
        end = schema.index(";", schema.index(body.group(1), body.end()) + len(body.group(1))) + 1
        verb = "CREATE OR REPLACE FUNCTION" if replace else "CREATE FUNCTION"
        out.append(re.sub(r"^CREATE (?:OR REPLACE )?FUNCTION", verb, schema[start:end]))
    return out


script = ("-- pg_morlet 0.3.12 -> 0.3.13 (generated by tests/gen_upgrade.py; do not edit).\n"
          "-- Time anchors (#393, #383): morlet_enable_time_anchors, morlet_add_time_anchors, morlet_revise_time_anchor,\n"
          "-- morlet_sample_utc, morlet_utc_to_samples, morlet_utc_to_sample and morlet_time_axis_version (new,\n"
          "-- experimental) with their internal helpers; morlet_enable_row_security covers <collection>_time_anchors.\n"
          "\\echo Use \"ALTER EXTENSION pg_morlet UPDATE TO '0.3.13'\" to load this file. \\quit\n\n"
          + "\n\n".join([d for n in NEW for d in definitions(n, False)]
                        + [d for n in REPLACED for d in definitions(n, True)]) + "\n")
if CHECK:
    if OUT.read_text() != script:
        sys.exit(f"{OUT.name} is stale: run tests/gen_upgrade.py")
    print(f"{OUT.name} up to date")
else:
    OUT.write_text(script)
    print(f"wrote {OUT.name}: {len(NEW)} new and {len(REPLACED)} replaced SQL functions")
