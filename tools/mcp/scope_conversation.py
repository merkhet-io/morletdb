#!/usr/bin/env python3
"""A scripted MCP conversation over a collection with a period that is out of search (#379, from #215).

  python tools/mcp/scope_conversation.py [TRANSCRIPT.md]      (DATABASE_URL: a database where the role may create
                                                              tables; it (re)creates public.mcp_scope_talk)

The questions an analyst would ask are answered by the server's own tools, in order. For every negative search
result (no hit), check() requires that the answer names what was searched (recordings, windows) and what was not
(the periods out of search, or an explicit statement that nothing was left out). The transcript, with every
question, tool call, the scope of every search and the verdict, is written as Markdown. Exit status 1 when a
negative answer does not state its scope.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import psycopg

sys.path.insert(0, str(Path(__file__).resolve().parent))
import morlet_mcp as m  # noqa: E402

C = "public.mcp_scope_talk"


def setup(url):
    """One recording, 400 s at 100 Hz from 2026-01-01T00:00Z; samples 10,000-30,000 compacted to level 3 (kept
    summaries only), so that period cannot be searched."""
    with psycopg.connect(url, autocommit=True) as conn:
        conn.execute("DROP TABLE IF EXISTS public.mcp_scope_talk CASCADE")
        for t in ("chunks", "segments", "envelopes", "episodes", "ledger", "memory_runs", "kept_summaries"):
            conn.execute(f"DROP TABLE IF EXISTS public.mcp_scope_talk_{t} CASCADE")
        conn.execute("""
            SELECT morlet_create_stream_collection('public','mcp_scope_talk'); SELECT morlet_enable_chunk_summaries('mcp_scope_talk');
            SELECT morlet_start_recording('mcp_scope_talk','A',100,'x','g','{"start":"2026-01-01T00:00:00Z","site":"S1"}',512,256,'zscore','none');
            SELECT morlet_append_chunks_raw('mcp_scope_talk','A',0,morlet_float8_le_bytes(ARRAY(
              SELECT round(100*sin(i/9.)*(1+(i%5000)/1000.))::float8 FROM generate_series(0,39999) i)),1000);
            SELECT morlet_enable_envelopes('mcp_scope_talk'); SELECT morlet_build_envelopes('mcp_scope_talk','A',512,256,100000);
            SELECT morlet_enable_memory('mcp_scope_talk');
            SELECT morlet_add_episodes('mcp_scope_talk','[{"recording_id":"A","start_sample":10000,"end_sample":30000}]');""")
        run = conn.execute("SELECT morlet_start_memory_run('mcp_scope_talk','test','1')").fetchone()[0]
        conn.execute("SELECT * FROM morlet_set_level('mcp_scope_talk',%s,'[{\"episode_id\":1,\"level\":3}]')", (run,))
        conn.execute("SELECT morlet_finish_memory_run('mcp_scope_talk',%s,'finished')", (run,))


# question, tool, arguments
CONVERSATION = [
    ("What is recorded here, and what can be searched?", "coverage", {"collection": C}),
    ("Find intervals like the first five seconds.", "search_similar",
     {"collection": C, "recording_id": "A", "start_sample": 0, "end_sample": 512, "top_k": 5, "evidence": False}),
    ("Did anything like it happen between 00:01:40 and 00:05:00?", "search_similar",
     {"collection": C, "recording_id": "A", "start_sample": 0, "end_sample": 512, "top_k": 5, "evidence": False,
      "time_from": "2026-01-01T00:01:40Z", "time_to": "2026-01-01T00:05:00Z"}),
    ("And at another site?", "search_similar",
     {"collection": C, "recording_id": "A", "start_sample": 0, "end_sample": 512, "top_k": 5, "evidence": False,
      "metadata_filter": '{"site": "S2"}'}),
]


def check(result: dict) -> tuple[bool, str]:
    """A negative search answer must say what was searched and what was not."""
    if result.get("hits"):
        return True, "has hits"
    scope = result.get("scope") or {}
    searched = "recordings" in scope and "searched_windows" in scope
    not_searched = bool(scope.get("not_searched_periods")) or scope.get("complete") is True
    if searched and scope.get("recordings") == 0 and "no recording matches" not in (scope.get("note") or ""):
        return False, "negative over no recording, but the note does not say that nothing was searched"
    if searched and not_searched:
        return True, "negative, scope stated"
    return False, f"negative without a scope (searched: {searched}, not searched stated: {not_searched})"


def run(url) -> tuple[bool, list[str]]:
    setup(url)
    os.environ["DATABASE_URL"] = url
    lines = ["# MCP conversation: negative results state their scope (#379)", "",
             "Generated by `tools/mcp/scope_conversation.py` against a collection with one recording (400 s at",
             "100 Hz); samples 10,000–30,000 (00:01:40–00:05:00) are compacted to memory level 3 and cannot be",
             "searched. Every search without a hit must say what it searched and what it did not.", ""]
    ok_all = True
    for i, (question, tool, args) in enumerate(CONVERSATION, 1):
        res = getattr(m, tool)(**args)
        lines += [f"## {i}. {question}", "", f"`{tool}({', '.join(f'{k}={v!r}' for k, v in args.items() if k != 'collection')})`", ""]
        if tool == "coverage":
            g = res["groups"][0]
            lines += [f"- recordings: {g['recordings']}, search states (s): `{json.dumps(g.get('search_states_s'))}`", ""]
            continue
        ok, why = check(res)
        ok_all &= ok
        scope = res.get("scope") or {}
        lines += [f"- hits: {len(res.get('hits', []))}",
                  f"- searched: {scope.get('recordings')} recording(s), {scope.get('searched_windows')} windows; "
                  f"complete: {scope.get('complete')}",
                  f"- not searched: `{json.dumps(scope.get('not_searched_periods'))}`",
                  f"- note: {scope.get('note')}",
                  f"- **check: {'pass' if ok else 'FAIL'}** ({why})", ""]
    lines.append(f"**Overall: {'every negative answer stated its scope' if ok_all else 'a negative answer did not state its scope'}.**")
    return ok_all, lines


def main():
    ok, lines = run(os.environ["DATABASE_URL"])
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if out:
        out.write_text("\n".join(lines) + "\n")
    else:
        print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
